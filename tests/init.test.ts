import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseRuleModules, runInit, scanTarget } from '../src/index.js';

describe('de-slop init command', () => {
  it('creates all target rule files in an empty workspace', async () => {
    const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'de-slop-init-'));
    try {
      const results = await runInit({
        cwd: tempDir,
        targets: ['cursor', 'claude', 'antigravity', 'gemini'],
      });

      expect(results.map((r) => r.status)).toEqual([
        'created',
        'created',
        'created',
        'created',
      ]);

      const claudeContent = await fs.readFile(path.join(tempDir, 'CLAUDE.md'), 'utf8');
      const antigravityContent = await fs.readFile(
        path.join(tempDir, '.antigravity', 'rules.md'),
        'utf8',
      );
      const geminiContent = await fs.readFile(
        path.join(tempDir, '.gemini', 'styleguide.md'),
        'utf8',
      );
      const cursorContent = await fs.readFile(path.join(tempDir, '.cursorrules'), 'utf8');

      expect(claudeContent).toContain('<!-- de-slop:start -->');
      expect(claudeContent).toContain('<!-- de-slop:end -->');
      expect(antigravityContent).toContain('Human Copywriting Rules');
      expect(geminiContent).toContain('Senior Code Quality Rules');
      expect(cursorContent).toContain('UI, Layout & Motion Rules');

      // Managed rule files generated by init should pass scan without self-flagging.
      const scanResult = await scanTarget(path.join(tempDir, 'CLAUDE.md'));
      expect(scanResult.findings).toHaveLength(0);
      expect(scanResult.score).toBe(100);
    } finally {
      await fs.rm(tempDir, { recursive: true, force: true });
    }
  });

  it('merges into existing user rules non-destructively and updates idempotently', async () => {
    const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'de-slop-merge-'));
    try {
      const claudePath = path.join(tempDir, 'CLAUDE.md');
      const userHeader = '# Project Team Guidelines\n\nAlways run `pnpm test` before commit.\n';
      await fs.writeFile(claudePath, userHeader, 'utf8');

      const firstRun = await runInit({
        cwd: tempDir,
        targets: ['claude'],
        modules: ['base', 'code'],
      });
      expect(firstRun[0]?.status).toBe('merged');

      const afterMerge = await fs.readFile(claudePath, 'utf8');
      expect(afterMerge.startsWith(userHeader.trimEnd())).toBe(true);
      expect(afterMerge).toContain('Senior Code Quality Rules');
      expect(afterMerge).not.toContain('Human Copywriting Rules');

      const secondRun = await runInit({
        cwd: tempDir,
        targets: ['claude'],
        modules: ['base', 'copy'],
      });
      expect(secondRun[0]?.status).toBe('updated');

      const afterUpdate = await fs.readFile(claudePath, 'utf8');
      expect(afterUpdate.startsWith(userHeader.trimEnd())).toBe(true);
      expect(afterUpdate).toContain('Human Copywriting Rules');
      expect(afterUpdate).not.toContain('Senior Code Quality Rules');
      expect(afterUpdate.match(/<!-- de-slop:start -->/g)).toHaveLength(1);
    } finally {
      await fs.rm(tempDir, { recursive: true, force: true });
    }
  });

  it('validates rule module parsing', () => {
    expect(parseRuleModules('ui, copy')).toEqual(['ui', 'copy']);
    expect(() => parseRuleModules('ui,unknown')).toThrow(/Unknown rule module/);
  });
});
